#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""Regenerate every number, table and figure of the paper from the run logs and compare them with paper/.

1. runs experiments/analysis/make_assets.py with PAPER_DIR set to a temporary folder (about three minutes);
2. compares every file of its generated/ with paper/generated byte by byte;
3. derives the layout variants of seven tables from the regenerated tables (paper/tools/derive_tables.py and
   make_tab_maint.py) and compares them with paper/derived byte by byte;
4. compares the figures pixel by pixel (needs pdftoppm from poppler, and Pillow): the figures that make_assets.py
   draws directly, and Figures 3, 4 and 6, which the paper draws with paper/tools/fig_*_kbs.py.

Usage:  python checks/check_regeneration.py
"""
import filecmp
import importlib.util
import os
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, ".."))
PAPER = os.path.join(ROOT, "paper")
MAKE = os.path.join(ROOT, "experiments", "analysis", "make_assets.py")
DIRECT_FIGS = ["fig_scan.pdf", "fig_ksweep.pdf", "fig_qps.pdf", "fig_maint.pdf", "fig_ablation.pdf"]
REDRAWN_FIGS = {"fig_pareto.pdf": "fig_pareto_kbs.py", "fig_fsweep.pdf": "fig_fsweep_kbs.py", "fig_cert.pdf": "fig_cert_kbs.py"}
DERIVE = ["derive_tables.py", "make_tab_maint.py"]
fails = []


def check(ok, msg):
    print(("PASS " if ok else "FAIL ") + msg)
    if not ok:
        fails.append(msg)


def pixels_equal(a, b, work):
    try:
        from PIL import Image, ImageChops
    except ImportError:
        return None
    imgs = []
    for i, pdf in enumerate((a, b)):
        base = os.path.join(work, f"cmp{i}")
        try:
            if subprocess.run(["pdftoppm", "-r", "110", "-png", "-singlefile", pdf, base], capture_output=True).returncode:
                return None
        except FileNotFoundError:
            return None
        imgs.append(Image.open(base + ".png").convert("RGB"))
    return imgs[0].size == imgs[1].size and ImageChops.difference(*imgs).getbbox() is None


def same_dir(new, ref, what):
    names = sorted(os.listdir(new))
    diff = [n for n in names if not os.path.exists(os.path.join(ref, n))
            or not filecmp.cmp(os.path.join(new, n), os.path.join(ref, n), shallow=False)]
    check(not diff, f"{what}: {len(names)} files identical byte by byte" + (f", differing: {diff}" if diff else ""))
    extra = sorted(set(os.listdir(ref)) - set(names))
    check(not extra, f"{what}: no file in paper/ that the scripts do not produce" + (f" (extra: {extra})" if extra else ""))


def main():
    tmp = tempfile.mkdtemp(prefix="certrefine_regen_")
    try:
        # 1-2. numbers, method-name macros, tables and the directly drawn figures
        env = dict(os.environ, PAPER_DIR=tmp)
        out = subprocess.run([sys.executable, MAKE], env=env, capture_output=True, text=True, encoding="utf-8", errors="replace")
        log = out.stdout + out.stderr
        open(os.path.join(HERE, "make_assets_last_run.log"), "w", encoding="utf-8").write(log)
        check(out.returncode == 0, "make_assets.py ran without error (output in checks/make_assets_last_run.log)")
        check("ERROR" not in log, "make_assets.py reported no failed claim (no ERROR line)")
        missing = [line for line in log.splitlines() if line.startswith("MISSING")]
        print("INFO inputs reported missing (both gaps are stated in the paper):", missing)
        same_dir(os.path.join(tmp, "generated"), os.path.join(PAPER, "generated"), "generated/")

        # 3. layout variants of tables 5, 6, 8, 9, 10, 13 and 14
        os.makedirs(os.path.join(tmp, "tools"))
        os.makedirs(os.path.join(tmp, "derived"))
        for script in DERIVE:
            shutil.copy(os.path.join(PAPER, "tools", script), os.path.join(tmp, "tools", script))
            r = subprocess.run([sys.executable, os.path.join(tmp, "tools", script)], cwd=tmp, capture_output=True, text=True)
            check(r.returncode == 0, f"{script} ran without error" + (f": {r.stderr.strip()[-300:]}" if r.returncode else ""))
        same_dir(os.path.join(tmp, "derived"), os.path.join(PAPER, "derived"), "derived/")

        # 4. figures
        for f in DIRECT_FIGS:
            eq = pixels_equal(os.path.join(tmp, "figs", f), os.path.join(PAPER, "figs", f), tmp)
            if eq is None:
                print(f"SKIP {f}: pdftoppm or Pillow not available")
            else:
                check(eq, f"{f}: identical pixels")
        sys.path.insert(0, os.path.join(PAPER, "tools"))
        for f, script in REDRAWN_FIGS.items():
            spec = importlib.util.spec_from_file_location(script[:-3], os.path.join(PAPER, "tools", script))
            mod = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(mod)
            mod.OUT = os.path.join(tmp, "redrawn_" + f)
            mod.main()
            eq = pixels_equal(mod.OUT, os.path.join(PAPER, "figs", f), tmp)
            if eq is None:
                print(f"SKIP {f}: pdftoppm or Pillow not available")
            else:
                check(eq, f"{f} (drawn by paper/tools/{script}): identical pixels")
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    print(f"\n== {len(fails)} check(s) failed")
    sys.exit(1 if fails else 0)


if __name__ == "__main__":
    main()
